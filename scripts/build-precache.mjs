import {readFile,writeFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const DEFAULT_ROOT=new URL('../',import.meta.url),sha=bytes=>createHash('sha256').update(bytes).digest('hex');

async function collect(root,files,directory){
  for(const item of await readdir(new URL(directory,root),{withFileTypes:true})){
    const path=`${directory}${item.name}`;
    if(item.isDirectory())await collect(root,files,`${path}/`);else files.add(path);
  }
}

export async function renderPrecache(root=DEFAULT_ROOT){
  const files=new Set(['index.html','styles.css','veil.css','manifest.webmanifest']);
  await collect(root,files,'src/veil/');
  await collect(root,files,'assets/');
  await collect(root,files,'data/');
  await collect(root,files,'vendor/');
  // Every source module in main is current. Historical entrypoints belong in Git history.
  for(const item of await readdir(new URL('src/',root)))if(item.endsWith('.js'))files.add(`src/${item}`);
  const entries=[];
  for(const path of [...files].sort())entries.push({path,sha256:sha(await readFile(new URL(path,root)))});
  const assetVersion=sha(JSON.stringify(entries)).slice(0,16),swURL=new URL('sw.js',root);
  let sw=await readFile(swURL,'utf8');
  const marker=`/* PRECACHE_ASSET_VERSION:${assetVersion} */`;
  if(/\/\* PRECACHE_ASSET_VERSION:[0-9a-f]{16} \*\//.test(sw))sw=sw.replace(/\/\* PRECACHE_ASSET_VERSION:[0-9a-f]{16} \*\//,marker);else sw=`${marker}\n${sw}`;
  const version=sha(JSON.stringify(entries)+sw).slice(0,16);
  const manifest=`// Generated by scripts/build-precache.mjs; do not edit.\nself.PRECACHE_VERSION=${JSON.stringify(version)};\nself.PRECACHE_FILES=${JSON.stringify(entries,null,2)};\n`;
  return {entries,sw,manifest,version};
}

export async function buildPrecache({root=DEFAULT_ROOT,check=false}={}){
  const rendered=await renderPrecache(root);
  if(check){
    const [committedSw,committedManifest]=await Promise.all([
      readFile(new URL('sw.js',root),'utf8'),
      readFile(new URL('precache-manifest.js',root),'utf8'),
    ]);
    const stale=[];
    if(committedSw!==rendered.sw)stale.push('sw.js');
    if(committedManifest!==rendered.manifest)stale.push('precache-manifest.js');
    if(stale.length)throw new Error(`Generated PWA artifact(s) are stale: ${stale.join(', ')}. Run node scripts/build-precache.mjs and commit the result.`);
    return rendered;
  }
  await Promise.all([
    writeFile(new URL('sw.js',root),rendered.sw),
    writeFile(new URL('precache-manifest.js',root),rendered.manifest),
  ]);
  return rendered;
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  try{
    const result=await buildPrecache({check:process.argv.includes('--check')});
    console.log(`${process.argv.includes('--check')?'Offline release is current':'Offline release '+result.version}: ${result.entries.length} verified assets`);
  }catch(error){
    console.error(error.message);
    process.exitCode=1;
  }
}
