import {readFile,writeFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url),sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const files=new Set(['index.html','styles.css','veil.css','manifest.webmanifest']);
async function collect(directory){for(const item of await readdir(new URL(directory,root),{withFileTypes:true})){const path=`${directory}${item.name}`;if(item.isDirectory())await collect(`${path}/`);else files.add(path);}}
await collect('src/veil/');await collect('assets/');await collect('data/');await collect('vendor/');
// Every source module in main is current. Historical entrypoints belong in Git history.
for(const item of await readdir(new URL('src/',root)))if(item.endsWith('.js'))files.add(`src/${item}`);
const entries=[];for(const path of [...files].sort())entries.push({path,sha256:sha(await readFile(new URL(path,root)))});
const assetVersion=sha(JSON.stringify(entries)).slice(0,16),swURL=new URL('sw.js',root);
let sw=await readFile(swURL,'utf8');
const marker=`/* PRECACHE_ASSET_VERSION:${assetVersion} */`;
if(/\/\* PRECACHE_ASSET_VERSION:[0-9a-f]{16} \*\//.test(sw))sw=sw.replace(/\/\* PRECACHE_ASSET_VERSION:[0-9a-f]{16} \*\//,marker);else sw=`${marker}\n${sw}`;
await writeFile(swURL,sw);
const version=sha(JSON.stringify(entries)+sw).slice(0,16);
await writeFile(new URL('precache-manifest.js',root),`// Generated by scripts/build-precache.mjs; do not edit.\nself.PRECACHE_VERSION=${JSON.stringify(version)};\nself.PRECACHE_FILES=${JSON.stringify(entries,null,2)};\n`);
console.log(`Offline release ${version}: ${entries.length} verified assets`);
