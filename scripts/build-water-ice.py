"""GenIce3 3.1.1 (MIT), https://genice-dev.github.io/GenIce3/
genice3 1h -r 5 5 5 -s 124 > /tmp/ice.gro
python scripts/build-water-ice.py /tmp/ice.gro > src/water-ice-sites.js
GROMACS nm, middle basal slab, radial crop; only translation and uniform scale.
"""
import json
import sys
import numpy as np
from scipy.spatial.transform import Rotation

lines = open(sys.argv[1]).read().splitlines()
waters = np.array([[float(x) for x in line[20:].split()] for line in lines[2:-1]]).reshape(-1, 3, 3)
box = np.array(lines[-1].split(), dtype=float)
oxygen = waters[:, 0] - box / 2
slab = np.where(abs(oxygen[:, 1]) < .34)[0]
sites = sorted(slab, key=lambda i: np.linalg.norm(oxygen[i, [0, 2]]))[:72]
base = min(oxygen[i, 1] for i in sites)
print('// Generated by scripts/build-water-ice.py. Oxygen xyz, then local-to-world xyzw.')
print('export const crystal = [')
for i in sites:
    h = waters[i, 1:] - waters[i, 0]
    h -= box * np.round(h / box)
    h /= np.linalg.norm(h, axis=1)[:, None]
    x, y = h[1] - h[0], h[1] + h[0]
    x /= np.linalg.norm(x)
    y /= np.linalg.norm(y)
    q = Rotation.from_matrix(np.column_stack((x, y, np.cross(x, y)))).as_quat()
    pos = (oxygen[i] - [0, base, 0]) * 2.23 + [0, .31, 0]
    assert .3 <= pos[1] <= 1.83 and np.linalg.norm(pos[[0, 2]]) < 2.55
    print('  ' + json.dumps(np.round(np.r_[pos, q], 6).tolist()) + ',')
print('];')
